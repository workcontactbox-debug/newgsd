function renderArticles(list = articles){

    articleGrid.innerHTML = "";

    articleCount.textContent =
        `${list.length} ${list.length === 1 ? "Article" : "Articles"}`;

    if(!list.length){

        articleGrid.innerHTML = `
            <div style="
                grid-column:1/-1;
                padding:70px 20px;
                text-align:center;
                background:white;
                border:1px solid #dfe6ec;
                border-radius:20px;
            ">
                <div style="
                    font-family:Manrope,sans-serif;
                    font-size:24px;
                    font-weight:800;
                    color:#0F2339;
                ">
                    No articles found
                </div>

                <p style="
                    margin-top:10px;
                    color:#667484;
                ">
                    Try a different search term.
                </p>
            </div>
        `;

        return;
    }

    list.forEach(article=>{

        const originalIndex =
            articles.indexOf(article);

        const card =
            document.createElement("article");

        card.className =
            "article-card";

        card.innerHTML = `

            <div class="card-image">

                <img
                    src="${article.image}"
                    alt="${escapeHTML(article.title)}"
                    loading="lazy"
                >

                <div class="card-number">
                    ${String(originalIndex + 1).padStart(2,"0")}
                </div>

            </div>

            <div class="card-body">

                <div class="card-tag">
                    ${escapeHTML(article.tag)}
                </div>

                <h3 class="card-title">
                    ${escapeHTML(article.title)}
                </h3>

                <p class="card-description">
                    ${escapeHTML(article.description)}
                </p>

                <button
                    class="read-btn"
                    onclick="openArticle(${originalIndex})"
                >
                    Read Article
                    <span>→</span>
                </button>

            </div>
        `;

        articleGrid.appendChild(card);
    });
}


function escapeHTML(value){

    return value
        .replace(/&/g,"&amp;")
        .replace(/</g,"&lt;")
        .replace(/>/g,"&gt;")
        .replace(/"/g,"&quot;")
        .replace(/'/g,"&#039;");
}


