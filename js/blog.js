const MIN_ZOOM = 0.85;
const PREFERRED_MAX_ZOOM = 1.25;
const ZOOM_STEP = 0.05;

let currentZoom = 1;
let dynamicMaxZoom = PREFERRED_MAX_ZOOM;
let noticeTimer = null;

/* =========================================================
   ARTICLE NAVIGATION
========================================================= */

function updateArticleNavigation(){

    const total =
        articles.length;

    const isFirst =
        currentArticleIndex <= 0;

    const isLast =
        currentArticleIndex >= total - 1;

    previousArticleBtn.disabled =
        isFirst;

    nextArticleBtn.disabled =
        isLast;

    previousArticleBtn.title =
        isFirst
            ? "No Previous Article"
            : `Previous: ${articles[currentArticleIndex - 1].title}`;

    nextArticleBtn.title =
        isLast
            ? "No Next Article"
            : `Next: ${articles[currentArticleIndex + 1].title}`;
}


function openPreviousArticle(){

    if(currentArticleIndex <= 0){
        return;
    }

    openArticle(
        currentArticleIndex - 1
    );
}


function openNextArticle(){

    if(
        currentArticleIndex < 0 ||
        currentArticleIndex >= articles.length - 1
    ){
        return;
    }

    openArticle(
        currentArticleIndex + 1
    );
}

/* =========================================================
   SAFE MAX ZOOM
========================================================= */

function calculateSafeMaxZoom(){

    if(!articleScroll || !articleContent){
        return PREFERRED_MAX_ZOOM;
    }

    const scrollWidth =
        articleScroll.clientWidth;

    if(!scrollWidth){
        return PREFERRED_MAX_ZOOM;
    }

    const naturalWidth =
        articleContent.offsetWidth;

    if(!naturalWidth){
        return PREFERRED_MAX_ZOOM;
    }

    const safeWidth =
        Math.max(1,scrollWidth - 4);

    let calculated =
        safeWidth / naturalWidth;

    calculated =
        Math.min(
            PREFERRED_MAX_ZOOM,
            calculated
        );

    calculated =
        Math.max(
            MIN_ZOOM,
            calculated
        );

    return Number(
        calculated.toFixed(2)
    );
}

/* =========================================================
   UPDATE ZOOM
========================================================= */

function updateZoom(){

    dynamicMaxZoom =
        calculateSafeMaxZoom();

    if(currentZoom > dynamicMaxZoom){
        currentZoom =
            dynamicMaxZoom;
    }

    articleContent.style.setProperty(
        "--article-zoom",
        currentZoom
    );

    zoomResetBtn.textContent =
        `${Math.round(currentZoom * 100)}%`;

    zoomInBtn.disabled =
        currentZoom >= dynamicMaxZoom;

    zoomOutBtn.disabled =
        currentZoom <= MIN_ZOOM;

    zoomInBtn.style.opacity =
        zoomInBtn.disabled ? ".45" : "1";

    zoomOutBtn.style.opacity =
        zoomOutBtn.disabled ? ".45" : "1";

    zoomInBtn.style.cursor =
        zoomInBtn.disabled
            ? "not-allowed"
            : "pointer";

    zoomOutBtn.style.cursor =
        zoomOutBtn.disabled
            ? "not-allowed"
            : "pointer";
}

/* =========================================================
   ZOOM NOTICE
========================================================= */

function showZoomNotice(message){

    clearTimeout(noticeTimer);

    zoomNotice.textContent =
        message;

    zoomNotice.classList.add("show");

    noticeTimer =
        setTimeout(()=>{

            zoomNotice.classList.remove("show");

        },3200);
}

/* =========================================================
   SET ZOOM
========================================================= */

function setZoom(newZoom){

    dynamicMaxZoom =
        calculateSafeMaxZoom();

    const requestedZoom =
        Number(newZoom.toFixed(2));

    if(requestedZoom > dynamicMaxZoom){

        currentZoom =
            dynamicMaxZoom;

        updateZoom();

        if(dynamicMaxZoom >= PREFERRED_MAX_ZOOM){

            showZoomNotice(
                "You are already at the maximum zoom level. Further zooming is disabled to keep the article fully within the reading area."
            );

        }else{

            showZoomNotice(
                `This screen allows a maximum zoom of ${Math.round(dynamicMaxZoom * 100)}%. Further zooming is disabled to keep the article fully visible without going outside the screen.`
            );

        }

        return;
    }

    if(requestedZoom < MIN_ZOOM){

        currentZoom =
            MIN_ZOOM;

        updateZoom();

        showZoomNotice(
            "You are already at the minimum zoom level. Further zooming out is disabled for comfortable reading."
        );

        return;
    }

    const previousZoom =
        currentZoom;

    currentZoom =
        requestedZoom;

    updateZoom();

    if(currentZoom > previousZoom){

        showZoomNotice(
            `Zoom increased to ${Math.round(currentZoom * 100)}%.`
        );

    }else if(currentZoom < previousZoom){

        showZoomNotice(
            `Zoom decreased to ${Math.round(currentZoom * 100)}%.`
        );
    }
}

