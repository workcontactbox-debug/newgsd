/* =========================================================
   KEYBOARD ZOOM + ARTICLE NAVIGATION
========================================================= */

document.addEventListener(
    "keydown",
    function(event){

        if(!modal.classList.contains("active")){
            return;
        }

        if(
            event.key === "ArrowLeft" &&
            !event.ctrlKey &&
            !event.metaKey
        ){

            event.preventDefault();

            openPreviousArticle();

            return;
        }

        if(
            event.key === "ArrowRight" &&
            !event.ctrlKey &&
            !event.metaKey
        ){

            event.preventDefault();

            openNextArticle();

            return;
        }

        if(
            event.key === "+" ||
            event.key === "="
        ){

            event.preventDefault();

            setZoom(
                Number(
                    (currentZoom + ZOOM_STEP)
                    .toFixed(2)
                )
            );
        }

        if(event.key === "-"){

            event.preventDefault();

            setZoom(
                Number(
                    (currentZoom - ZOOM_STEP)
                    .toFixed(2)
                )
            );
        }

        if(event.key === "0"){

            event.preventDefault();

            currentZoom = 1;

            updateZoom();

            showZoomNotice(
                "Zoom reset to 100%."
            );
        }

    }
);

