/* =========================================================
   TOUCH SWIPE
========================================================= */

let touchStartX = 0;
let touchEndX = 0;

articleScroll.addEventListener(
    "touchstart",
    function(event){

        touchStartX =
            event.changedTouches[0].screenX;

    },
    {
        passive:true
    }
);


articleScroll.addEventListener(
    "touchend",
    function(event){

        touchEndX =
            event.changedTouches[0].screenX;

        const difference =
            touchStartX - touchEndX;

        if(Math.abs(difference) < 70){
            return;
        }

        if(difference > 0){

            openNextArticle();

        }else{

            openPreviousArticle();

        }

    },
    {
        passive:true
    }
);

